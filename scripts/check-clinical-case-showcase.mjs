import assert from 'node:assert/strict';
import { readFileSync, existsSync } from 'node:fs';
import { resolve } from 'node:path';
import { Script } from 'node:vm';
const root=resolve('public/clinical-case-workspace');
const html=readFileSync(resolve(root,'index.html'),'utf8');
const text=html;
assert(!existsSync(resolve(root,'project-data.json')),'Knowledge metadata export must not be published');
assert(!/457|>66<|>28<|非空.*关联|知识库快照|汇总快照|project-data\.json/.test(html),'Stale knowledge statistics or export link');
assert(html.includes('架构与知识关联'));
assert(!/\/Users\/|file:\/\/|collection:\/\/|https:\/\/app\.notion\.com|github_pat_|ghp_[A-Za-z0-9]{20,}/.test(text),'Private identifier or local path');
assert(!/\b[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}\b/.test(text),'Private entity ID');
assert(!/\bfetch\s*\(|XMLHttpRequest|WebSocket|sendBeacon/.test(html),'Unexpected network API');
assert(html.includes("connect-src 'none'"));
const ids=[...html.matchAll(/\bid="([^"]+)"/g)].map(m=>m[1]);
assert.equal(new Set(ids).size,ids.length,'Duplicate IDs');
for(const m of html.matchAll(/aria-controls="([^"]+)"/g))assert(ids.includes(m[1]),'Missing tab panel');
for(const m of html.matchAll(/<img\b[^>]*src="([^"]+)"/g))assert(existsSync(resolve(root,m[1])),'Missing local image');
for(const m of html.matchAll(/<script>([\s\S]*?)<\/script>/g))new Script(m[1]);
assert.equal((html.match(/<button\b[^>]*role="tab"/g)||[]).length,4);
const project=JSON.parse(readFileSync('content/projects/clinical-case-workspace.json','utf8'));
assert.equal(project.demoUrl,'/clinical-case-workspace/');
assert(!project.repoUrl,'Private source repository must not become a public link');
console.log('Clinical project dossier: qualitative architecture, privacy, local assets, script syntax, tabs and project entry checks passed.');
